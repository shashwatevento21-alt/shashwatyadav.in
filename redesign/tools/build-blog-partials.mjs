// Generates the blog plugin's NEW header/footer from the redesign's shared partials, so the blog and the static pages cannot drift apart.
// Site paths become {{BASE}}/... (the plugin fills in /_preview for the private preview and an empty string after go-live);
// /blog/, /classes and external links are left as they are.   node redesign/tools/build-blog-partials.mjs
import fs from 'node:fs';
import { part, root } from './lib.mjs';

const KEEP = /^\/(classes|blog|category|wp-|chatbot|feed|tag|author)/;
const base = (html) => html.replace(/\b(href|src|action)="(\/[^"]*)"/g, (m, a, u) => (u.startsWith('//') || KEEP.test(u) ? m : `${a}="{{BASE}}${u}"`));

let header = part('header').trim();
header = header.replace('<a class="nav-link" href="/blog/">', '<a class="nav-link" href="/blog/" aria-current="page">');
const footer = part('footer').trim() + '\n\n' + part('floating').trim();
const dir = new URL('wordpress/shashwat-blog-layout/partials-v2/', root);
fs.mkdirSync(dir, { recursive: true });
const note = '<!-- generated by redesign/tools/build-blog-partials.mjs from redesign/partials: do not edit by hand -->\n';
fs.writeFileSync(new URL('header.html', dir), note + base(header) + '\n');
fs.writeFileSync(new URL('footer.html', dir), note + base(footer) + '\n');
console.log('blog partials written:', header.length, 'and', footer.length, 'bytes before path tokens');
